class CsvMetricsSink(MetricsSink):
    """File-backed :class:`~dagrun.protocols.MetricsSink` writing CSV rows.

    Carries the fixed run context (explicit output directory, git SHA, machine id, and the
    per-step provenance columns) as construction state; the scheduler passes only the
    varying per-call data. The explicit output directory is created on demand."""

    def __init__(
        self,
        output_dir: str | Path,
        *,
        git_sha: str,
        machine_id_value: str | None = None,
        profile_base_sha: str | None = None,
        enforcement_kind: str = "unverified",
        runner_name: str = "local",
        ipc: object = "",
        cache_miss_pct: object = "",
        run_id: str | None = None,
    ) -> None:
        self.output_dir = output_dir
        self.git_sha = git_sha
        self.machine_id_value = machine_id() if machine_id_value is None else machine_id_value
        self.profile_base_sha = profile_base_sha
        self.enforcement_kind = enforcement_kind
        self.runner_name = runner_name
        self.ipc = ipc
        self.cache_miss_pct = cache_miss_pct
        #: Identifies the ONE DAG execution this sink records. Minted here, at sink
        #: construction, rather than per batch: a run that records its rows in more than one
        #: call must still be one group, and a sink that re-minted per call would silently
        #: split it.
        self.run_id = new_run_id() if run_id is None else run_id

    def start_run_window(self) -> RunWindow:
        """Open the whole-run window bound to this sink's context."""
        return PerfWindow.start(
            output_dir=self.output_dir,
            git_sha=self.git_sha,
            machine_id_value=self.machine_id_value,
            ipc=self.ipc,
            cache_miss_pct=self.cache_miss_pct,
        )

    def record_step_profiles(
        self, rows: Sequence[Mapping[str, object]], *, jobs: int
    ) -> str | None:
        """Append per-step profile ``rows`` (accumulated during the run) to durable storage.

        Delegates to :func:`append_step_profiles`; ``jobs`` is the active-step ceiling and is
        stamped as the existing ``outer_jobs`` field on every row. Rows are recorded regardless
        of run outcome. Returns the CSV path as a string, or ``None`` when recording was skipped
        (a visible warning is emitted)."""
        path = append_step_profiles(
            self.output_dir,
            rows,
            git_sha=self.git_sha,
            outer_jobs=jobs,
            profile_base_sha=self.profile_base_sha,
            enforcement_kind=self.enforcement_kind,
            runner_name=self.runner_name,
            run_id=self.run_id,
        )
        return None if path is None else str(path)

    def record_step_timeseries(
        self, rows: Sequence[Mapping[str, object]], *, jobs: int
    ) -> str | None:
        """Persist opt-in interval samples in this execution's dedicated trace CSV."""
        path = append_step_timeseries(
            self.output_dir,
            rows,
            git_sha=self.git_sha,
            outer_jobs=jobs,
            profile_base_sha=self.profile_base_sha,
            enforcement_kind=self.enforcement_kind,
            runner_name=self.runner_name,
            run_id=self.run_id,
        )
        return None if path is None else str(path)
