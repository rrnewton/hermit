def machine_id() -> str:
    """Per-machine identifier from ``/proc/cpuinfo`` 'model name' (spaces -> underscores,
    then non ``[A-Za-z0-9_-]`` stripped). Falls back to the hostname, then ``"unknown"``.
    Mirrors run_benchmark-style CPU naming so rows group cleanly per machine."""
    try:
        with open("/proc/cpuinfo") as f:
            for line in f:
                if line.startswith("model name"):
                    name = line.split(":", 1)[1].strip().replace(" ", "_")
                    return re.sub(r"[^A-Za-z0-9_-]", "", name)
    except OSError:
        pass
    return re.sub(r"[^A-Za-z0-9_-]", "", os.uname().nodename) or "unknown"


def new_run_id() -> str:
    """A fresh identifier for ONE DAG execution: nanoseconds since the epoch and the runner
    PID, both hex, concatenated.

    Uniqueness comes from the pair, not from either half. Two runs on one host cannot share
    a start nanosecond, and a PID reused after a clock step cannot collide with the earlier
    run that held it. The value is opaque: a reader groups rows by equality and never parses
    it, so nothing depends on how it was built."""
    return f"{time.time_ns():016x}{os.getpid():08x}"


def nproc() -> int:
    """Cores this run could actually use (respects CPU affinity / cgroup pin)."""
    try:
        return len(os.sched_getaffinity(0))
    except (AttributeError, OSError):
        return os.cpu_count() or 1


def _own_cgroup_relpath() -> str | None:
    """This process's cgroup-v2 path relative to the mount root, e.g. ``/user.slice/foo.scope``."""
    try:
        with open("/proc/self/cgroup") as f:
            for line in f:
                # cgroup-v2 unified line: "0::/user.slice/..."
                if line.startswith("0::"):
                    return line.split("::", 1)[1].strip() or "/"
    except OSError:
        pass
    return None


def effective_cpu_quota(
    *, mount_root: str | Path = "/sys/fs/cgroup", relpath: str | None = None
) -> str:
    """The CPU quota actually BINDING this process, as a normalized ``<quota>_<period>`` string.

    ``mount_root`` and ``relpath`` select the hierarchy to inspect; by default this process's
    own cgroup under the standard cgroup-v2 mount.

    Walks the selected cgroup and every ancestor up to the mount root and returns the most
    restrictive `cpu.max` (smallest quota/period ratio), because a cgroup-v2 quota is enforced by
    the whole ancestor chain, not just the leaf. Returns ``"max"`` when nothing in the chain
    constrains CPU, and ``"unknown"`` when the hierarchy cannot be read at all.

    The mount-root ``/sys/fs/cgroup/cpu.max`` must NOT be used for this: on an ordinary host that
    file does not exist, so the quota half of :func:`container_class` degenerates to the constant
    ``unknown`` and stops distinguishing anything. That matters because a slice several levels up
    is where a CPU bandwidth cap typically lives -- a step can run with a full-width affinity mask
    and still be held to a fraction of a core by an ancestor's quota. Two genuinely different
    containers then share one key, the speedup model fits a single curve across both populations,
    and it recommends the wide machine's width to the constrained one.
    """
    if relpath is None:
        relpath = _own_cgroup_relpath()
    if relpath is None:
        return "unknown"
    best_ratio: float | None = None
    best_text = "max"
    seen_any = False
    root = Path(mount_root)
    node = root / relpath.lstrip("/")
    while True:
        try:
            raw = (node / "cpu.max").read_text().strip()
            seen_any = True
            parts = raw.split()
            if len(parts) == 2 and parts[0] != "max":
                quota, period = int(parts[0]), int(parts[1])
                if period > 0:
                    ratio = quota / period
                    if best_ratio is None or ratio < best_ratio:
                        best_ratio, best_text = ratio, f"{quota}_{period}"
        except (OSError, ValueError):
            pass
        if node == root or root not in node.parents:
            break
        node = node.parent
    if not seen_any:
        return "unknown"
    return best_text


def container_class() -> str:
    """Stable CPU-container key: affinity width plus the CPU quota binding this process.

    Both halves matter and they constrain independently: a cpuset narrows WHICH cpus (reflected in
    ``nproc()`` via the affinity mask) while ``cpu.max`` caps total CPU BANDWIDTH. Samples taken
    under different containers must not share a key, or the speedup model fits one curve across
    incompatible populations."""
    return f"affinity{nproc()}_cpu-max-{effective_cpu_quota()}"


def _whole_run_csv_name(machine_id_value: str | None = None) -> str:
    """The whole-run summary CSV file name for a machine: ``<machine_id>.csv``."""
    mid = machine_id() if machine_id_value is None else machine_id_value
    return f"{mid}.csv"


def _step_profiles_csv_name() -> str:
    """The per-step profile CSV file name:
    ``step_profiles_<machine_id>_<container_class>.csv``."""
    return f"step_profiles_{machine_id()}_{container_class()}.csv"


def store_paths(output_dir: str | Path) -> list[Path]:
    """The profile-store file paths a single ``run``/``sweep`` writes into ``output_dir``: the
    whole-run summary (``<machine_id>.csv``) and the per-step profile CSV
    (``step_profiles_<machine_id>_<container_class>.csv``).

    The CLI reports EXACTLY these (filtered to files that exist) rather than globbing the whole
    store — a persistent store also holds prior runs' other-``container_class`` variants on the same
    machine, and globbing would over-report files this run never wrote."""
    base = Path(output_dir)
    return [base / _whole_run_csv_name(), base / _step_profiles_csv_name()]


def _proc_stat_busy_jiffies() -> int | None:
    """Sum of all non-idle jiffies from the aggregate 'cpu ' line of ``/proc/stat``.
    Busy = everything except idle + iowait (iowait is not CPU-burning work). ``None`` when
    ``/proc/stat`` is unreadable or malformed."""
    try:
        with open("/proc/stat") as f:
            first = f.readline()
    except OSError:
        return None
    parts = first.split()
    if not parts or parts[0] != "cpu":
        return None
    vals = [int(x) for x in parts[1:]]
    idle = vals[3] if len(vals) > 3 else 0      # idle jiffies
    iowait = vals[4] if len(vals) > 4 else 0    # iowait jiffies (when present)
    return sum(vals) - idle - iowait


