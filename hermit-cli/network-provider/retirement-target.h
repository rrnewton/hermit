static int ap_check_copy_image(FILE *input) {
    unsigned char actual[256];
    for(size_t i=0;i<sizeof(ap_copy_image_slices)/sizeof(ap_copy_image_slices[0]);i++) {
        const struct ap_copy_image_slice *slice=&ap_copy_image_slices[i];
        if(fseek(input,slice->offset,SEEK_SET))return -1;
        for(size_t at=0;at<slice->size;) {
            size_t size=slice->size-at;if(size>sizeof(actual))size=sizeof(actual);
            if(fread(actual,1,size,input)!=size) {if(!ferror(input))errno=ENODATA;return -1;}
            if(memcmp(actual,slice->bytes+at,size)) {errno=ESTALE;return -1;}
            at+=size;
        }
    }
    return 0;
}
