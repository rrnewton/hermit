/* Both int3 and optimized classic callbacks expose raw ctx.ip=site+1.
 * Retain that observed PC; no function-IP helper sentinel supplies identity. */
static __attribute__((always_inline)) inline int ap_file_post_site(
    unsigned long long entry_ip,unsigned long long post_ip) {
    const unsigned long long delta=AP_FILE_FDGET_RETURN_OFFSET-AP_FILE_ENTRY_OFFSET;
    return entry_ip && post_ip && entry_ip<=~0ULL-delta && post_ip==entry_ip+delta;
}
static __attribute__((always_inline)) inline int ap_file_caller_site(
    unsigned long long observed_ip,unsigned long long return_ip,int post) {
    const unsigned long long offset=post?AP_FILE_FDGET_RETURN_OFFSET:AP_FILE_ENTRY_OFFSET;
    const unsigned long long delta=AP_FILE_CALLER_RETURN_DELTA-offset-1;
    return observed_ip>offset+1 && return_ip && observed_ip<=~0ULL-delta &&
        return_ip==observed_ip+delta;
}
